"""Matt for Unity (trainer container, after check_model.py):
  python matt/model_info.py
- Assets/MuJoCo/matt/matt_unity.xml: the robot only, to drop into a race scene's single MuJoCo model next to the
  dogs. No option / size / statistic (the race scene's MjGlobalSettings already carries the same contract, and the
  importer would add a second settings object), no floor, light, assets or keyframes, and only the four sensors
  MattController reads (contact sensors name the trainer's floor geom).
- Assets/Scripts/MattSpec.cs: the contract Unity checks the regenerated model against (docs/matt/model_summary.json).
"""
import json
import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco

HERE = Path(__file__).resolve().parent
SRC = HERE / "assets" / "matt_porace.xml"
UNITY = Path("/assets/MuJoCo/matt/matt_unity.xml")
SPEC = Path("/assets/Scripts/MattSpec.cs")
SENSORS = {"local_linvel_pelvis", "gyro_pelvis", "orientation_pelvis", "upvector_torso"}
GAIT_HZ = 1.375   # stock G1 joystick samples U(1.25, 1.5) per episode; Unity runs the mean

# Testbed (parity harness, Assets/Scenes/MattTestbed.unity): the trainer scene - option block, floor - minus keyframes
# and the sensors Unity does not use.
tb = ET.parse(SRC).getroot()
for tag in ("size", "keyframe"):
  for e in tb.findall(tag):
    tb.remove(e)
for e in list(tb.find("sensor")):
  if e.get("name") not in {"local_linvel_pelvis", "gyro_pelvis", "orientation_pelvis", "upvector_torso"}:
    tb.find("sensor").remove(e)
ET.indent(tb)
Path("/assets/MuJoCo/matt").mkdir(parents=True, exist_ok=True)
Path("/assets/MuJoCo/matt/matt_testbed.xml").write_text("<!-- generated by training/matt/model_info.py: do not edit -->\n" + ET.tostring(tb, encoding="unicode") + "\n")

root = ET.parse(SRC).getroot()
for tag in ("option", "size", "statistic", "keyframe", "asset", "visual"):
  for e in root.findall(tag):
    root.remove(e)
wb = root.find("worldbody")
for e in list(wb):
  if e.tag != "body":
    wb.remove(e)
sens = root.find("sensor")
for e in list(sens):
  if e.get("name") not in SENSORS:
    sens.remove(e)
root.set("model", "matt")
UNITY.parent.mkdir(parents=True, exist_ok=True)
ET.indent(root)
UNITY.write_text("<!-- generated by training/matt/model_info.py from matt_porace.xml: do not edit -->\n" + ET.tostring(root, encoding="unicode") + "\n")

full = mujoco.MjModel.from_xml_path(str(SRC))
robot = mujoco.MjModel.from_xml_path(str(UNITY))
assert (robot.nq, robot.nv, robot.nu) == (full.nq, full.nv, full.nu)
assert abs(robot.body_mass.sum() - full.body_mass.sum()) < 1e-9

s = json.loads(Path("/docs/matt/model_summary.json").read_text())
fl = lambda xs: ", ".join(f"{x:g}f" for x in xs)
q = lambda xs: ", ".join(f'"{x}"' for x in xs)
SPEC.write_text(f"""// GENERATED by training/matt/model_info.py from docs/matt/model_summary.json. Do not edit by hand.
namespace PoRace {{

/// <summary>Matt contract: G1 joint layout (29 position-controlled joints) on Matt's body, race physics: 250 Hz,
/// 50 Hz control (decimation 5). Joint order = qpos[7:], qvel[6:], ctrl, action and observation slices.</summary>
public static class MattSpec {{
  public const int Nu = {s["nu"]};
  public const float SimDt = {s["timestep"]:g}f;
  public const int Decimation = 5;
  public const float ActionScale = 0.5f;
  public const int ObsDim = 103;   // linvel 3, gyro 3, gravity 3, command 3, q - default 29, qvel 29, last action 29, phase cos/sin 4
  public const double Mass = {s["mass"]!r};
  public const float GaitHz = {GAIT_HZ}f;
  public const float HomeHeight = {s["init_qpos"][2]:g}f;   // pelvis height at knees_bent
  public const float PelvisRestZ = {float(root.find("worldbody/body").get("pos").split()[2]):g}f;   // pelvis body at MuJoCo zero pose (= the rig's Hips head)
  public const float ImpRatio = {float(tb.find("option").get("impratio")):g}f;   // the race model is compiled at this when Matt races (dogs alone: 100)
  public static readonly string[] Joints = {{ {q(s["joints"])} }};
  public static readonly float[] DefaultPose = {{ {fl(s["default_pose"])} }};
  public static readonly float[] Kp = {{ {fl(s["kp"])} }};
  public static readonly float[] ForceMax = {{ {fl(r[1] for r in s["forcerange"])} }};
}}

}}
""")
print(f"wrote {UNITY} (nq {robot.nq}, nu {robot.nu}, {robot.nsensor} sensors, mass {robot.body_mass.sum():.3f}) and {SPEC}")
